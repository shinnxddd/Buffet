    private FuentePixel() { }

    /** Todo a mayúsculas y con las tildes separadas (Á = A + marca), que es como las dibuja esta fuente. */
    private static String preparar(String texto) {
        return Normalizer.normalize(texto.toUpperCase(), Normalizer.Form.NFD);
    }

    static int ancho(String texto, int u) {
        int n = 0;
        for (char c : preparar(texto).toCharArray()) {
            if (c < 0x300 || c > 0x36F) {
                n++;
            }
        }
        return Math.max(0, n * AVANCE - 1) * u;
    }

    static int alto(int u) {
        return ALTO * u;
    }

    /** (x, y) es la esquina superior izquierda de la primera letra. */
    static void dibujar(Graphics2D g, String texto, int x, int y, int u, Color color) {
        g.setColor(color);
        int cx = x;
        int ultimoX = x;
        for (char c : preparar(texto).toCharArray()) {
            if (c >= 0x300 && c <= 0x36F) {
                marca(g, c, ultimoX, y, u);
                continue;
            }
            String[] glifo = GLIFOS.get(c);
            if (glifo == null) {
                glifo = GLIFOS.get('?');
            }
            for (int fila = 0; fila < ALTO; fila++) {
                String f = glifo[fila];
                int col = 0;
                while (col < 5) {   // une los puntos contiguos en una sola barra: menos rectángulos que pintar
                    if (f.charAt(col) == '#') {
                        int fin = col;
                        while (fin + 1 < 5 && f.charAt(fin + 1) == '#') {
                            fin++;
                        }
                        g.fillRect(cx + col * u, y + fila * u, (fin - col + 1) * u, u);
                        col = fin + 1;
                    } else {
                        col++;
                    }
                }
            }
            ultimoX = cx;
            cx += AVANCE * u;
        }
    }

    private static void marca(Graphics2D g, char marca, int x, int y, int u) {
        switch (marca) {
            case 0x301:   // tilde aguda
                g.fillRect(x + 3 * u, y - 2 * u, u, u);
                g.fillRect(x + 2 * u, y - u, u, u);
                break;
            case 0x308:   // diéresis
                g.fillRect(x + u, y - 2 * u, u, u);
                g.fillRect(x + 3 * u, y - 2 * u, u, u);
                break;
            case 0x303:   // virgulilla (Ñ)
                g.fillRect(x + u, y - u, u, u);
                g.fillRect(x + 2 * u, y - 2 * u, 2 * u, u);
                g.fillRect(x + 4 * u, y - u, u, u);
                break;
            default:
                break;
        }
    }

    static void centrado(Graphics2D g, String texto, int cx, int y, int u, Color color) {
        dibujar(g, texto, cx - ancho(texto, u) / 2, y, u, color);
    }

    /** Letras con borde de 1 punto (para que se lean sobre cualquier fondo). */
    static void conContorno(Graphics2D g, String texto, int x, int y, int u, Color color, Color contorno) {
        for (int dx = -1; dx <= 1; dx++) {
            for (int dy = -1; dy <= 1; dy++) {
                if (dx != 0 || dy != 0) {
                    dibujar(g, texto, x + dx * u, y + dy * u, u, contorno);
                }
            }
        }
        dibujar(g, texto, x, y, u, color);
    }
